import { Check, ChevronDown, FlaskConical, Menu, MonitorCog } from 'lucide-react'
import { USE_MOCK } from '@/api'
import { Badge } from '@/components/ui/badge'
import { Button } from '@/components/ui/button'
import {
  DropdownMenu,
  DropdownMenuContent,
  DropdownMenuItem,
  DropdownMenuLabel,
  DropdownMenuSeparator,
  DropdownMenuTrigger,
} from '@/components/ui/dropdown-menu'
import { Select, SelectContent, SelectItem, SelectTrigger, SelectValue } from '@/components/ui/select'
import { Tooltip, TooltipContent, TooltipTrigger } from '@/components/ui/tooltip'
import { BUSINESSES, DEMO_USERS, demoUser, type Business } from '@/lib/demo'
import { useSession } from '@/lib/session'

export function TopBar({ onOpenMenu }: { onOpenMenu: () => void }) {
  const { business, role, setBusiness, setRole } = useSession()
  const me = demoUser(role)

  return (
    <header className="sticky top-0 z-20 flex h-14 items-center gap-2 border-b bg-card px-4 sm:gap-3">
      <Button variant="ghost" size="icon" className="lg:hidden" onClick={onOpenMenu} aria-label="Open menu">
        <Menu />
      </Button>

      <Select value={business} onValueChange={(v) => setBusiness(v as Business)}>
        <SelectTrigger className="w-auto min-w-0 max-w-[55vw] sm:max-w-none" aria-label="Business">
          <SelectValue />
        </SelectTrigger>
        <SelectContent>
          {BUSINESSES.map((b) => (
            <SelectItem key={b.id} value={b.id}>
              {b.name} <span className="hidden text-muted-foreground sm:inline">· {b.kind}</span>
            </SelectItem>
          ))}
        </SelectContent>
      </Select>

      <Tooltip>
        <TooltipTrigger asChild>
          <Badge variant="outline" className="hidden border-warning/40 bg-warning-soft text-warning sm:inline-flex">
            <FlaskConical aria-hidden />
            Synthetic data
          </Badge>
        </TooltipTrigger>
        <TooltipContent>All shops, people, suppliers and figures are generated by our team.</TooltipContent>
      </Tooltip>

      {USE_MOCK && (
        <Tooltip>
          <TooltipTrigger asChild>
            <Badge variant="outline" className="hidden sm:inline-flex">
              <MonitorCog aria-hidden />
              Mock API
            </Badge>
          </TooltipTrigger>
          <TooltipContent>Answers come from src/mocks in the browser, not the FastAPI server.</TooltipContent>
        </Tooltip>
      )}

      <div className="ml-auto" />

      <DropdownMenu>
        <DropdownMenuTrigger asChild>
          <Button variant="ghost" className="h-auto gap-2 px-2 py-1">
            <span className="grid size-8 place-items-center rounded-full bg-primary text-xs font-semibold text-primary-foreground">
              {initials(me.display_name)}
            </span>
            <span className="hidden text-left leading-tight sm:block">
              <span className="block text-sm font-medium">{me.display_name}</span>
              <span className="block text-xs text-muted-foreground">{me.label}</span>
            </span>
            <ChevronDown className="size-4 text-muted-foreground" aria-hidden />
          </Button>
        </DropdownMenuTrigger>
        <DropdownMenuContent align="end" className="w-72">
          <DropdownMenuLabel>Demo login · switch user</DropdownMenuLabel>
          <DropdownMenuSeparator />
          {DEMO_USERS.map((u) => (
            <DropdownMenuItem key={u.role} onSelect={() => setRole(u.role)} className="items-start">
              <div className="flex-1">
                <div className="font-medium">
                  {u.display_name} · {u.label}
                </div>
                <div className="text-xs text-muted-foreground">{u.can}</div>
              </div>
              {u.role === role && <Check className="mt-0.5" aria-label="Current user" />}
            </DropdownMenuItem>
          ))}
          <DropdownMenuSeparator />
          <div className="flex items-center gap-1.5 px-2 py-1.5 text-xs text-warning sm:hidden">
            <FlaskConical className="size-3.5" aria-hidden /> Synthetic data only
          </div>
        </DropdownMenuContent>
      </DropdownMenu>
    </header>
  )
}

function initials(name: string): string {
  return name
    .split(' ')
    .map((w) => w[0])
    .join('')
    .slice(0, 2)
    .toUpperCase()
}
